CREATE TABLE IF NOT EXISTS public.document_loans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id bigint NULL,
    usuario_nome text NOT NULL,
    usuario_id_udesc text NOT NULL,
    documento text NOT NULL,
    codigo_classificacao text,
    caixa text,
    setor text,
    data_emprestimo timestamptz NOT NULL DEFAULT now(),
    data_devolucao timestamptz,
    status text NOT NULL DEFAULT 'Emprestado',
    observacoes text,
    criado_em timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.document_loans
    ALTER COLUMN inventory_id DROP NOT NULL;

CREATE INDEX IF NOT EXISTS idx_document_loans_inventory_id
    ON public.document_loans (inventory_id);

CREATE INDEX IF NOT EXISTS idx_document_loans_status
    ON public.document_loans (status);