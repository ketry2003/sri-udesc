def mostrar_erro_tabela(exc):
    mensagem = str(exc)
    if "document_loans" in mensagem or "PGRST205" in mensagem:
        st.error("A tabela de empréstimos ainda não foi criada no Supabase.")
        with st.expander("Abra o SQL para criar a tabela", expanded=True):
            st.code(SQL_TABELA, language="sql")
        return True
    return False


def rotulo_item(item):
    return " | ".join(
        [
            str(item.get("id", "-")),
            str(item.get("item_documental") or item.get("tipo_documental") or "-"),
            str(item.get("codigo_classificacao") or "-"),
            f"Caixa: {item.get('caixa') or '-'}",
            f"Setor: {item.get('setor') or '-'}",
        ]
    )


def resumo_conteudo(item):
    observacoes = str(item.get("observacoes") or "").strip()
    assunto = ""

    for trecho in observacoes.split(" | "):
        if trecho.lower().startswith("assunto:"):
            assunto = trecho.split(":", 1)[1].strip()
            break

    return assunto or observacoes or "-"


def documentos_da_caixa(item, itens):
    caixa = str(item.get("caixa") or "").strip()
    setor = str(item.get("setor") or "").strip()

    if not caixa:
        return []

    return [
        registro
        for registro in itens
        if str(registro.get("caixa") or "").strip() == caixa
        and str(registro.get("setor") or "").strip() == setor
    ]


def corresponde_busca_inventario(item, consulta):
    consulta = consulta.strip().casefold()
    if not consulta:
        return True

    campos = [
        item.get("item_documental"),
        item.get("tipo_documental"),
        item.get("assunto"),
        item.get("observacoes"),
        item.get("caixa"),
    ]
    texto = " ".join(str(campo or "") for campo in campos).casefold()
    return consulta in texto


def exportar_excel(dataframe):
    arquivo = BytesIO()
    with pd.ExcelWriter(arquivo, engine="openpyxl") as writer:
        dataframe.to_excel(writer, index=False, sheet_name="Empréstimos")
    return arquivo.getvalue()


try:
    itens = list_inventory_items()
except Exception as exc:
    st.error(f"Não foi possível carregar o inventário: {exc}")
    itens = []
aba_novo, aba_devolucoes, aba_historico = st.tabs(
    ["Novo empréstimo", "Devoluções", "Histórico"]
)

with aba_novo:
    st.subheader("Registrar novo empréstimo")

    origem = st.radio(
        "Origem do documento",
        ["Inventário", "Preenchimento manual"],
        horizontal=True,
        key="origem_emprestimo",
    )

    item = None
    if origem == "Inventário":
        consulta_inventario = st.text_input(
            "Pesquisar por documento, assunto ou número da caixa",
            placeholder="Ex.: contrato, férias, 012",
            key="busca_emprestimo_inventario",
        )
        itens_filtrados = [
            registro
            for registro in itens
            if corresponde_busca_inventario(registro, consulta_inventario)
        ]
        st.caption(f"Itens encontrados: {len(itens_filtrados)}")

        opcoes = {rotulo_item(item): item for item in itens_filtrados}
        rotulo_selecionado = st.selectbox(
            "Selecione o documento",
            [""] + list(opcoes),
            key="emprestimo_item",
        )
        if rotulo_selecionado:
            item = opcoes[rotulo_selecionado]

            itens_da_caixa = documentos_da_caixa(item, itens)
            if itens_da_caixa:
                st.subheader(
                    f"Conteúdo da caixa {item.get('caixa') or '-'}"
                )
                st.caption(
                    "Documentos cadastrados no inventário para a mesma caixa e setor."
                )
                conteudo_caixa = pd.DataFrame(
                    [
                        {
                            "Tipo/documento": (
                                registro.get("item_documental")
                                or registro.get("tipo_documental")
                                or "-"
                            ),
                            "Assunto/conteúdo": resumo_conteudo(registro),
                            "Código": registro.get("codigo_classificacao") or "-",
                            "Datas limite": registro.get("datas_limite") or "-",
                        }
                        for registro in itens_da_caixa
                    ]
                )
                st.dataframe(conteudo_caixa, use_container_width=True, hide_index=True)

    with st.form("form_novo_emprestimo"):
        documento_manual = st.text_input(
            "Documento *",
            value=(item.get("item_documental", "") if item else ""),
            disabled=origem == "Inventário",
        )
        colunas = st.columns(3)
        codigo_manual = colunas[0].text_input(
            "Código de classificação",
            value=(item.get("codigo_classificacao", "") if item else ""),
            disabled=origem == "Inventário",
        )
        caixa_manual = colunas[1].text_input(
            "Caixa", value=(item.get("caixa", "") if item else ""),
            disabled=origem == "Inventário",
        )
        setor_manual = colunas[2].text_input(
            "Setor *", value=(item.get("setor", "") if item else ""),
            disabled=origem == "Inventário",
        )
        usuario_nome = st.text_input("Nome do usuário *")
        usuario_id_udesc = st.text_input("ID UDESC (opcional)")
        setores_disponiveis = sorted(
            {
                str(registro.get("setor") or "").strip()
                for registro in itens
                if str(registro.get("setor") or "").strip()
            }
        )
        setor_usuario_opcao = st.selectbox(
            "Setor de trabalho do usuário *",
            [""] + setores_disponiveis + ["Outro"],
            key="setor_usuario_opcao",
        )
        setor_usuario = setor_usuario_opcao
        if setor_usuario_opcao == "Outro":
            setor_usuario = st.text_input(
                "Informe o setor de trabalho *",
                key="setor_usuario_outro",
            )
        observacoes = st.text_area("Observações")
        enviar = st.form_submit_button("Registrar empréstimo")

    if enviar:
        if not documento_manual.strip():
            st.error("Informe o documento.")
        elif not usuario_nome.strip():
            st.error("Informe o nome do usuário.")
        elif not setor_manual.strip():
            st.error("Informe o setor.")
        elif not setor_usuario.strip():
            st.error("Informe o setor de trabalho do usuário.")
        else:
            try:
                registrar_emprestimo(
                    {
                        "inventory_id": item.get("id") if item else None,
                        "documento": documento_manual.strip(),
                        "codigo_classificacao": codigo_manual.strip(),
                        "caixa": caixa_manual.strip(),
                        "setor": setor_manual.strip(),
                        "usuario_nome": usuario_nome.strip(),
                        "usuario_id_udesc": usuario_id_udesc.strip(),
                        "setor_usuario": setor_usuario.strip(),
                        "observacoes": observacoes.strip(),
                    }
                )
                st.success("Empréstimo registrado com sucesso.")
                st.rerun()
            except Exception as exc:
                if not mostrar_erro_tabela(exc):
                    st.error(f"Erro ao registrar empréstimo: {exc}")

with aba_devolucoes:
    st.subheader("Documentos emprestados")
    try:
        emprestados = listar_documentos_emprestados()
    except Exception as exc:
        mostrar_erro_tabela(exc)
        emprestados = []

    if not emprestados:
        st.info("Nenhum documento está atualmente emprestado.")
    else:
        for emprestimo in emprestados:
            with st.container(border=True):
                colunas = st.columns(4)
                colunas[0].write(f"**Documento:** {emprestimo.get('documento') or '-'}")
                colunas[1].write(f"**Caixa:** {emprestimo.get('caixa') or '-'}")
                colunas[2].write(f"**Setor:** {emprestimo.get('setor') or '-'}")
                colunas[3].write(
                    f"**Usuário:** {emprestimo.get('usuario_nome') or '-'}"
                )
                st.caption(
                    f"ID UDESC: {emprestimo.get('usuario_id_udesc') or '-'} | "
                    f"Setor do usuário: {emprestimo.get('setor_usuario') or '-'} | "
                    f"Empréstimo: {emprestimo.get('data_emprestimo') or '-'}"
                )

                if st.button(
                    "Registrar devolução",
                    key=f"devolver_{emprestimo.get('id')}",
                    type="primary",
                ):
                    try:
                        registrar_devolucao(
                            emprestimo.get("id"),
                            observacoes="Devolução registrada pela interface",
                        )
                        st.success("Devolução registrada com sucesso.")
                        st.rerun()
                    except Exception as exc:
                        st.error(f"Erro ao registrar devolução: {exc}")

with aba_historico:
    st.subheader("Histórico de empréstimos")
    try:
        historico = listar_emprestimos()
    except Exception as exc:
        mostrar_erro_tabela(exc)
        historico = []
    dataframe = pd.DataFrame(historico)

    if dataframe.empty:
        st.info("Nenhum registro de empréstimo encontrado.")
    else:
        colunas = st.columns(4)
        filtro_usuario = colunas[0].text_input("Usuário", key="filtro_emprestimo_usuario")
        filtro_id = colunas[1].text_input("ID UDESC", key="filtro_emprestimo_id")
        filtro_documento = colunas[2].text_input(
            "Documento", key="filtro_emprestimo_documento"
        )
        filtro_status = colunas[3].selectbox(
            "Status",
            ["Todos", "Emprestado", "Devolvido"],
            key="filtro_emprestimo_status",
        )

        filtros = {
            "usuario_nome": filtro_usuario,
            "usuario_id_udesc": filtro_id,
            "documento": filtro_documento,
        }
        for campo, valor in filtros.items():
            if valor.strip() and campo in dataframe.columns:
                dataframe = dataframe[
                    dataframe[campo]
                    .astype(str)
                    .str.contains(valor.strip(), case=False, na=False)
                ]

        if filtro_status != "Todos" and "status" in dataframe.columns:
            dataframe = dataframe[dataframe["status"] == filtro_status]

        st.dataframe(dataframe, use_container_width=True)

        if not dataframe.empty:
            st.download_button(
                "Exportar histórico para Excel",
                data=exportar_excel(dataframe),
                file_name="historico_emprestimos.xlsx",
                mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            )
