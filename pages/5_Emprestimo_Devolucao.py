from services.db import (
    listar_documentos_emprestados,
    listar_emprestimos,
    list_inventory_items,
    registrar_devolucao,
    registrar_emprestimo,
)


st.set_page_config(
    page_title="Empréstimo e Devolução de Documentos",
    layout="wide",
)
st.title("Empréstimo e devolução de documentos")

